import type { Paint, Part } from './types';

// Vehicle models. Coordinates are fractions: x along length (+front), y across width (+right),
// z of height. Cars use extruded side profiles (`p`); trucks/aircraft use boxes (`b`).
// Wheels are added by the renderer from the movement type.

const b = (x0: number, x1: number, y0: number, y1: number, z0: number, z1: number, paint: Paint, tag?: Part['tag']): Part =>
  ({ x: [x0, x1], y: [y0, y1], z: [z0, z1], paint, ...(tag ? { tag } : {}) });

/** Profile part: a side silhouette extruded across [y0, y1]. */
const p = (pts: [number, number][], y0: number, y1: number, paint: Paint): Part => {
  const xs = pts.map((q) => q[0]), zs = pts.map((q) => q[1]);
  return { x: [Math.min(...xs), Math.max(...xs)], y: [y0, y1], z: [Math.min(...zs), Math.max(...zs)], paint, profile: pts };
};

